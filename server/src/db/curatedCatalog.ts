export function seedCuratedCatalog(db: Database.Database): void {
  try {
    // Ensure system-curated user exists
    db.prepare(`
      INSERT OR IGNORE INTO users (id, email, password_hash, display_name, role, gender)
      VALUES ('system-curated', 'curated@fitsync.com', 'none', 'FITSYNC Editorial Boutique', 'admin', 'unisex')
    `).run();

    const insert = db.prepare(`
      INSERT OR REPLACE INTO wardrobe_items (
        id, user_id, image_path, thumbnail_path, original_filename,
        category, subcategory, primary_color, secondary_colors, pattern,
        texture, material, style, formality, season, use_cases,
        ai_confidence, ai_analyzed, is_favorite, is_available, custom_name,
        brand, price, product_url, is_curated, gender
      ) VALUES (
        @id, 'system-curated', @image_url, @image_url, @original_filename,
        @category, @subcategory, @primary_color, @secondary_colors, @pattern,
        @texture, @material, @style, @formality, @season, @use_cases,
        0.98, 1, 0, 1, @name,
        @brand, @price, @product_url, 1, @gender
      )
    `);

    for (const item of CURATED_CATALOG_ITEMS) {
      insert.run({
        id: item.id,
        name: item.name,
        original_filename: `${item.id}.webp`,
        category: item.category,
        subcategory: item.subcategory,
        gender: item.gender,
        primary_color: item.primary_color,
        secondary_colors: JSON.stringify(item.secondary_colors),
        pattern: item.pattern,
        texture: item.texture,
        material: item.material,
        style: item.style,
        formality: item.formality,
        season: item.season,
        use_cases: JSON.stringify(item.use_cases),
        brand: item.brand,
        price: item.price,
        product_url: item.product_url,
        image_url: item.image_url,
      });
    }

    console.log(`Seeded ${CURATED_CATALOG_ITEMS.length} high-fashion curated catalog items with gender tagging.`);
  } catch (err) {
    console.warn('Failed to seed curated catalog items:', err);
  }
}
